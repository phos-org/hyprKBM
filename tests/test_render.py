import subprocess
import textwrap

import pytest

from hyprkbm import luaval, render as render_module
from hyprkbm.apply import DRY_RUN
from hyprkbm.luaval import NotReproducible
from hyprkbm.catalogue import load_catalogue
from hyprkbm.reader import read_config
from hyprkbm.render import bind_line, render

CAT = load_catalogue()

HAND = """\
    local mainMod = "SUPER"
    hl.bind(mainMod .. " + F", hl.dsp.exec_cmd("dolphin"))
    hl.bind(mainMod .. " + P", hl.dsp.window.pseudo())
    hl.define_submap("resize", "escape", function()
        hl.bind("SUPER + F", hl.dsp.window.resize())
    end)
"""

MODEL = {
    "version": 1,
    "submaps": [{"name": "move", "reset": "escape"}],
    "binds": [
        {"id": "b1", "keys": "SUPER + F", "submap": "",
         "action": {"kind": "exec_cmd", "args": {"cmd": "nautilus"}},
         "description": "File manager",
         "replaces": {"keys": "SUPER + F", "submap": "", "fingerprint": 'exec_cmd:["dolphin"]'}},
        {"id": "b2", "keys": "SUPER + B",
         "action": {"kind": "exec_cmd", "args": {"cmd": "firefox"}},
         "flags": {"repeating": False, "locked": True}},
        {"id": "b3", "keys": "right", "submap": "move",
         "action": {"kind": "window.move", "args": {"direction": "right"}}},
    ],
    "unbinds": [{"keys": "SUPER + P", "submap": "", "fingerprint": "window.pseudo:[]"}],
}

EXPECTED = '''\
-- Generated by hyprKBM from keybinds.json. Edits here are overwritten: change
-- binds in the hyprKBM panel, or edit keybinds.json and run `hyprkbm --apply`.

-- Undo this file's previous run first: it is loaded again whenever the
-- watcher reconnects, and hl.bind adds a bind rather than replacing one. A
-- reload resets Lua, which empties this list along with everything else.
for _, k in ipairs(__hyprkbm_binds or {}) do pcall(k.remove, k) end
__hyprkbm_binds = {}
local function __hyprkbm_bind(...)
    local k = hl.bind(...)
    table.insert(__hyprkbm_binds, k)
    return k
end

-- Submaps
hl.define_submap("move", function()
    __hyprkbm_bind("escape", hl.dsp.submap("reset"))
end)

-- SUPER + F: replaces binds from hyprland.lua
hl.unbind("SUPER + F")
hl.define_submap("resize", function()
    __hyprkbm_bind("SUPER + F", hl.dsp.window.resize())
end)

-- SUPER + P: replaces binds from hyprland.lua
hl.unbind("SUPER + P")

-- hyprKBM's binds
__hyprkbm_bind("SUPER + F", hl.dsp.exec_cmd("nautilus"), { description = "File manager" })
__hyprkbm_bind("SUPER + B", hl.dsp.exec_cmd("firefox"), { locked = true })
hl.define_submap("move", function()
    __hyprkbm_bind("right", hl.dsp.window.move({ direction = "right" }))
end)
'''


def hand(paths, source=HAND):
    paths.entry.write_text(textwrap.dedent(source))
    return read_config(paths)


def test_render_writes_submaps_then_replaced_combos_then_own_binds(paths):
    assert render(MODEL, hand(paths), CAT) == EXPECTED


def test_an_empty_model_renders_only_the_header_and_preamble(paths):
    text = render({"version": 1, "submaps": [], "binds": [], "unbinds": []}, hand(paths), CAT)
    assert text.startswith("-- Generated by hyprKBM")
    assert "__hyprkbm_binds = {}" in text
    assert "bind(" not in text.replace("local function __hyprkbm_bind(...)", "").replace("hl.bind(...)", "")


def test_every_bind_goes_through_the_undoable_helper(paths):
    text = render(MODEL, hand(paths), CAT)
    assert "for _, k in ipairs(__hyprkbm_binds or {}) do pcall(k.remove, k) end" in text
    direct = [l for l in text.splitlines() if "hl.bind(" in l]
    assert direct == ["    local k = hl.bind(...)"]


def test_bind_line_omits_empty_options():
    assert bind_line("SUPER + C", {"dsp": "window.close", "args": []}, {}) == \
        '__hyprkbm_bind("SUPER + C", hl.dsp.window.close())'


def test_raw_lua_is_written_verbatim():
    assert bind_line("SUPER + G", {"raw": "function() hl.exec_cmd(\"x\") end"}, {}) == \
        '__hyprkbm_bind("SUPER + G", (\nfunction() hl.exec_cmd("x") end\n))'


def test_what_is_rendered_reads_back_as_intended(paths, tmp_path):
    """Round trip: the rendered file, run through the reader on its own, binds
    exactly hyprKBM's binds plus the re-created hand ones."""
    text = render(MODEL, hand(paths), CAT)
    paths.entry.write_text(text)

    result = read_config(paths)

    assert result.error is None
    assert [(b.submap, b.keys, b.fingerprint, b.opts) for b in result.binds] == [
        # The submap's way out is a real bind, so it can never trap the keyboard.
        ("move", "escape", 'submap:["reset"]', {}),
        ("resize", "SUPER + F", "window.resize:[]", {}),
        ("", "SUPER + F", 'exec_cmd:["nautilus"]', {"description": "File manager"}),
        ("", "SUPER + B", 'exec_cmd:["firefox"]', {"locked": True}),
        ("move", "right", 'window.move:[{"direction":"right"}]', {}),
    ]
    assert result.submaps[0]["name"] == "move"


@pytest.mark.parametrize("dsp", ["a b", "window.close()", "x;y", "1abc", "a..b", ""])
def test_a_dsp_that_is_not_dotted_identifiers_is_not_reproducible(dsp):
    with pytest.raises(NotReproducible):
        bind_line("SUPER + C", {"dsp": dsp, "args": []}, {})


def test_a_trailing_comment_in_raw_lua_cannot_swallow_the_rest_of_the_bind(paths):
    model = {"version": 1, "submaps": [], "unbinds": [], "binds": [
        {"id": "r1", "keys": "SUPER + G", "action": {"kind": "raw", "lua": "hl.dsp.window.close() -- note"},
         "description": "Close"}]}
    paths.entry.write_text(render(model, hand(paths), CAT))

    result = read_config(paths)

    assert result.error is None
    assert [(b.keys, b.opts) for b in result.binds] == [("SUPER + G", {"description": "Close"})]


HARNESS = r"""
live = {}
local function remove_record(rec)
    for i, r in ipairs(live) do
        if r == rec then table.remove(live, i) return end
    end
end
local function callable()
    return setmetatable({}, {
        __index = function(_, _) return callable() end,
        __call = function() return {} end,
    })
end
hl = {
    dsp = callable(),
    bind = function(keys, d, opts)
        local rec = { keys = keys }
        table.insert(live, rec)
        return { remove = function() remove_record(rec) end }
    end,
    unbind = function(keys)
        for i = #live, 1, -1 do
            if live[i].keys == keys then table.remove(live, i) end
        end
    end,
    define_submap = function(name, a, b)
        local f = type(a) == "function" and a or b
        if f then f() end
    end,
}
local rendered, dry = ...
dofile(rendered)
print(#live)
dofile(rendered)
print(#live)
local before = #(__hyprkbm_binds or {})
dofile(dry)
print(#live)
print(#(__hyprkbm_binds or {}) == before)
dofile(rendered)
print(#live)
"""


def run_twice_and_dry(paths, tmp_path, text):
    rendered = tmp_path / "rendered.lua"
    rendered.write_text(text, encoding="utf-8")
    dry = tmp_path / "dry.lua"
    dry.write_text("local chunk = assert(load(%s))\nchunk()\n"
                   % lua_long(DRY_RUN % luaval.string(str(rendered))), encoding="utf-8")
    harness = tmp_path / "harness.lua"
    harness.write_text(HARNESS, encoding="utf-8")
    res = subprocess.run([luaval.interpreter(), str(harness), str(rendered), str(dry)],
                         capture_output=True, text=True, encoding="utf-8", timeout=20)
    assert res.returncode == 0, res.stderr
    return res.stdout.split()


def lua_long(text):
    return "[==[" + text + "]==]"


def test_loading_keybinds_twice_or_through_the_dry_run_never_doubles_binds(paths, tmp_path):
    out = run_twice_and_dry(paths, tmp_path, render(MODEL, hand(paths), CAT))
    first, second, dry, untouched, after = out
    assert untouched == "true"
    assert int(first) > 0
    assert first == second == dry == after


def test_without_the_preamble_the_same_harness_sees_doubling(paths, monkeypatch, tmp_path):
    monkeypatch.setattr(render_module, "PREAMBLE", "local function __hyprkbm_bind(...) return hl.bind(...) end\n")
    out = run_twice_and_dry(paths, tmp_path, render(MODEL, hand(paths), CAT))
    assert out[0] != out[1]
